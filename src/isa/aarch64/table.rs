/* Flags */
const F_ALIAS: Aarch64Flags = (1 << 0);
const F_HAS_ALIAS: Aarch64Flags = (1 << 1);
const F_P1: Aarch64Flags = (1 << 2);
const F_P2: Aarch64Flags = (2 << 2);
const F_P3: Aarch64Flags = (3 << 2);
const F_COND: Aarch64Flags = (1 << 4);
const F_SF: Aarch64Flags = (1 << 5);
const F_SIZEQ: Aarch64Flags = (1 << 6);
const F_FPTYPE: Aarch64Flags = (1 << 7);
const F_SSIZE: Aarch64Flags = (1 << 8);
const F_T: Aarch64Flags = (1 << 9);
const F_GPRSIZE_IN_Q: Aarch64Flags = (1 << 10);
const F_LDS_SIZE: Aarch64Flags = (1 << 11);
const F_OPD0_OPT: Aarch64Flags = (1 << 12);
const F_OPD1_OPT: Aarch64Flags = (2 << 12);
const F_OPD2_OPT: Aarch64Flags = (3 << 12);
const F_OPD3_OPT: Aarch64Flags = (4 << 12);
const F_OPD4_OPT: Aarch64Flags = (5 << 12);
const fn F_DEFAULT(X: Aarch64Flags) -> Aarch64Flags {
    (((X) & 0x1f) << 15)
}
const F_CONV: Aarch64Flags = (1 << 20);
const F_PSEUDO: Aarch64Flags = (1 << 21);
const F_MISC: Aarch64Flags = (1 << 22);
const F_N: Aarch64Flags = (1 << 23);
const fn F_OD(X: Aarch64Flags) -> Aarch64Flags {
    (((X) & 0x7) << 24)
}
const F_LSE_SZ: Aarch64Flags = (1 << 27);


#[derive(Debug, Copy, Clone)]
pub struct Aarch64Opcode {
    /* The name of the mnemonic.  */
    name: &'static str,

    /* The opcode itself.  Those bits which will be filled in with
    operands are zeroes.  */
    opcode: Aarch64Insn,

    /* The opcode mask.  This is used by the disassembler.  This is a
    mask containing ones indicating those bits which must match the
    opcode field, and zeroes indicating those bits which need not
    match (and are presumably filled in by operands).  */
    mask: Aarch64Insn,

    /* Instruction class.  */
    iclass: Aarch64InsnClass,

    /* Which architecture variant provides this instruction.  */
    //const aarch64_feature_set *avariant;

    /* An array of operand codes.  Each code is an index into the
       operand table.  They appear in the order which the operands must
       appear in assembly code, and are terminated by a zero.  */
    operands: Operands,

    /* A list of operand qualifier code sequence.  Each operand qualifier
       code qualifies the corresponding operand code.  Each operand
       qualifier sequence specifies a valid opcode variant and related
       constraint on operands.  */
    //qualifiersList: Vec<aarch64_opnd_qualifier_seq_t>,

    /* Flags providing information about this instruction */
    flags: Aarch64Flags,
}

impl Aarch64Opcode {
    pub(crate) fn mnemonic(&self) -> &'static str {
        self.name
    }

    fn is_alias(&self) -> bool {
        self.flags & F_ALIAS != 0
    }

    fn is_conversion_alias(&self) -> bool {
        self.flags & F_CONV != 0
    }

    pub(crate) fn operands(&self) -> Vec<Aarch64Opnd> {
        match self.operands {
            Operands::Op0 => Vec::new(),
            Operands::Op1(a) => vec![a],
            Operands::Op2(a, b) => vec![a, b],
            Operands::Op3(a, b, c) => vec![a, b, c],
            Operands::Op4(a, b, c, d) => vec![a, b, c, d],
            Operands::Op5(a, b, c, d, e) => vec![a, b, c, d, e],
        }
    }
}

const fn Aarch64Opcode(
    name: &'static str,
    opcode: Aarch64Insn,
    mask: Aarch64Insn,
    iclass: Aarch64InsnClass,
    operands: Operands,
    flags: Aarch64Flags,
) -> Aarch64Opcode {
    Aarch64Opcode {
        name,
        opcode,
        mask,
        iclass,
        operands,
        flags,
    }
}

